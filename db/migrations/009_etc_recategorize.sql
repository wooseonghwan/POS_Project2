-- 009_etc_recategorize.sql
-- '기타(ETC)' 카테고리에 몰려 있던 바코드 상품 중 성격이 분명한 것들을 기존/신규 카테고리로 재분류.
-- 대상은 기타 카테고리 안에 있던 상품만 해당하며, 판매화면 노출여부(pos_grid_yn)는 변경하지 않음(기존 그대로 'Y' 유지).
--   - 금액이 상품명인 것(예: "100원", "1,000원") -> 신규 카테고리 '금액'(AMOUNT)
--   - 미끼/루어류 -> 기존 카테고리 '미끼'(BAIT)
--   - 모자류 -> 기존 카테고리 '모자'(HAT)
--   - 음료/주류(캔/병 등 액체류)만 -> 기존 카테고리 '음료'(DRINK, 주류/음료/식품)
-- 그 외 기타 성격이 애매한 상품(생활용품, 루어 아닌 장비, 간식/과자류 등)은 그대로 '기타'에 남김.

-- 1) 신규 '금액' 카테고리 추가
INSERT INTO code_tb (code_gbn, code_cd, code_nm, sort_no) VALUES
    ('POSCAT', 'AMOUNT', '금액', 10)
ON DUPLICATE KEY UPDATE code_nm = VALUES(code_nm);

-- 2) 금액 상품명 -> 금액(AMOUNT)
UPDATE product_tb SET poscat_cd = 'AMOUNT'
WHERE poscat_cd = 'ETC' AND barcode IN (
    '50001', '50002', '50003', '50004', '50005', '50006',
    '100000', '100001', '100300', '1003000'
);

-- 3) 미끼/루어 -> 미끼(BAIT)
UPDATE product_tb SET poscat_cd = 'BAIT'
WHERE poscat_cd = 'ETC' AND barcode IN (
    -- 생미끼/밑밥류
    '10001', '10002', '10003', '10004', '10005', '10006', '10007', '10008',
    '10009', '10010', '10011', '10012', '10013', '10014',
    -- 요즈리 애기(루어)
    '4940764553359', '4940764803706', '4940764504771', '4940764803553',
    '4940764553397', '4940764803669', '4940764553427', '4940764803126',
    '4940764078623', '4940764553434', '4940764553304',
    -- 한조 애기(루어)
    '495736490049', '495736490018', '495736490032',
    -- 삼봉 애기(루어)
    '2200000000997', '2200000000996', '2200000000995',
    -- 슈리켄/니켄 애기(루어)
    '4989801775156', '4998000783268', '4998000783312', '4998000783329'
);

-- 4) 모자 -> 모자(HAT)
UPDATE product_tb SET poscat_cd = 'HAT'
WHERE poscat_cd = 'ETC' AND barcode IN (
    '50024', '50025', '50026', '50027', '50028', '50029', '50030'
);

-- 5) 음료/주류(액체류) -> 음료(DRINK)
UPDATE product_tb SET poscat_cd = 'DRINK'
WHERE poscat_cd = 'ETC' AND barcode IN (
    '4005906404811', '4005906405139', '4005906405009',
    '50037', '50038', '50041'
);
